#!/bin/sh
# پشتیبانِ فوری از خطِ فرمانِ سرور — همان کاری که دکمهٔ «پشتیبان‌گیری همین حالا»
# در «تنظیمات ← پشتیبان‌گیری» می‌کند، و منتظرِ پایانش می‌ماند.
#
#   ./scripts/backup.sh
#
# فایل در والیومِ backups ساخته و به همهٔ مقصدهای فعال فرستاده می‌شود.
# رمز و مقصدها همان تنظیماتِ پنل‌اند؛ اول آنجا تنظیمشان کنید.
set -eu
cd "$(dirname "$0")/.."
exec docker compose exec -T app node scripts/kbz-backup.mjs backup
