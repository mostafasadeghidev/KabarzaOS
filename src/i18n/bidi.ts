/**
 * جهتِ یک مقدار درونِ جملهٔ ترجمه‌شده — LRI … PDI (یونیکد، «جداسازِ چپ‌به‌راست»).
 *
 * ⚠️ چرا نه کلاسِ `num` روی کلِ جمله: `num` جهتِ **کلِ** عنصر را LTR می‌کند و
 * آن‌وقت ترتیبِ کلمه‌های فارسی برعکس می‌شود — «۱–۲۰ از ۵۷ ردیف» خوانده می‌شد
 * «از ۵۷ ردیف ۱–۲۰»، و «ددلاین ۲۰۲۶-۱۰-۰۱» تاریخ را پیش از برچسب نشان می‌داد.
 * جمله باید جهتِ زبان را بگیرد و فقط خودِ مقدار LTR بماند.
 *
 * کی لازم است: مقداری که **درونش** جداکنندهٔ خنثی دارد و بی‌آن در متنِ
 * راست‌به‌چپ تکه‌تکه و وارونه می‌شود — بازه («۱–۲۰»، خطِ تیره خنثی است)،
 * شمارهٔ کارت و شبا با فاصله، تاریخ‌وساعت با فاصله. عددِ تنها، تاریخِ
 * `YYYY-MM-DD` و «۳/۷» خودشان درست می‌نشینند و این لازم ندارند.
 *
 * در JSX، جایی که مقدار عنصرِ جداست، `<span className="num">` همین کار را می‌کند؛
 * این برای مقداری است که **داخلِ** رشتهٔ ترجمه (جای‌گذاریِ `{x}`) می‌نشیند.
 */
export function ltr(value: string | number): string {
  return `\u2066${value}\u2069`;
}
