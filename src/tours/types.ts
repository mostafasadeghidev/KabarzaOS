/**
 * راهنمای تعاملی (۳.۱۹.۰) — تعریفِ راهنماها به‌صورتِ داده.
 *
 * هر راهنما یک ردیف از قدم‌هاست. هر قدم به یک عنصرِ صفحه اشاره می‌کند با برچسبِ ثابتِ
 * `data-tour="…"` (نه کلاسِ CSS)، تا اگر ظاهرِ صفحه عوض شد راهنما نشکند.
 *
 * ⚠️ متن‌ها (title / body) کلیدِ ترجمه‌اند — متنِ فارسی؛ موتور با t() نشانشان می‌دهد و استخراج‌گرِ
 * کلیدها (`title:` / `body:`) خودش پیدایشان می‌کند. پس همین‌جا فارسیِ کامل بنویسید، نه کلیدِ انگلیسی.
 */
import type { Permission, Role } from '@/domain/access/permissions';

/** آنچه موتور از کاربرِ جاری می‌داند — روی سرور ساخته می‌شود (server/tours.ts) و به مرورگر می‌آید. */
export interface TourCtx {
  roles: readonly Role[];
  /** مجوزهای مؤثر (نقش + per-user، با «مدیریت ⇐ مشاهده»). */
  perms: readonly Permission[];
  isOwner: boolean;
  /** مدیرِ تیم: دفتری را مدیریت می‌کند (hasTeamScope). */
  managesTeam: boolean;
  /** مدیرِ پروژه: دستِ‌کم روی یک پروژه تگِ pm دارد. */
  isPm: boolean;
  /** عضوِ تیم (نقشِ member). */
  isMember: boolean;
  /** کارفرمای خالص (client بدونِ member). */
  isClientOnly: boolean;
}

export const can = (c: TourCtx, p: Permission) => c.perms.includes(p);

/**
 * آیا کاربر در مسیرِ قدم است؟ مسیرِ بی «/» ِ پایانی **دقیقاً** همان صفحه است ('/projects' = فهرست)، و با «/»
 * هر صفحهٔ زیرش ('/projects/' = صفحهٔ هر پروژه). ⚠️ پیش از این پیشوند بود و '/projects' صفحهٔ یک پروژه را هم
 * «همین صفحه» حساب می‌کرد؛ قدمِ «افزودن پروژه» آنجا دنبالِ دکمه‌ای می‌گشت که فقط در فهرست هست.
 */
export const onPath = (pathname: string, p: string) => (p.endsWith('/') ? pathname.startsWith(p) : pathname === p);

export interface TourStep {
  /** شناسهٔ پایدارِ قدم در همین راهنما (برای ادامه دادن بعد از بارگذاریِ دوباره). */
  id: string;
  /**
   * مقدارِ `data-tour` ِ عنصری که روشن می‌شود. نبودن = کارتِ وسطِ صفحه (خوش‌آمد، جمع‌بندی).
   * اگر چند عنصر همین برچسب را دارند، اولینِ **دیدنی** انتخاب می‌شود (مثلاً منوی سایدبار یا منوی پایینِ گوشی).
   */
  target?: string;
  /** عنوانِ کوتاهِ کارت — متنِ فارسی (کلیدِ ترجمه). */
  title: string;
  /** توضیح — متنِ فارسی (کلیدِ ترجمه). یک تا سه جملهٔ کوتاه، خطابِ «شما». */
  body: string;
  /**
   * `info` (پیش‌فرض): فقط دیدن، با دکمهٔ «بعدی».
   * `click`: دکمهٔ «بعدی» نیست؛ کاربر باید خودش روی بخشِ روشن کلیک کند تا راهنما جلو برود.
   *   برای باز کردنِ منو/دیالوگ/صفحه — همان کاری که بعداً خودش می‌کند.
   */
  kind?: 'info' | 'click';
  /**
   * مسیری که این قدم در آن معنا دارد — قاعدهٔ `onPath`: '/projects' فقط فهرست، '/projects/' هر صفحهٔ زیرش. اگر کاربر جای دیگری باشد
   * کارتی با دکمهٔ «برو به آنجا» نشان داده می‌شود. برای قدم‌های پشتِ سرِ هم در یک صفحه کافی است اولی بگذارد،
   * ولی گذاشتن روی همه بی‌خطر است.
   */
  path?: string;
  /**
   * برای قدمِ `click` ِ ناوبری: راهنما وقتی جلو می‌رود که کاربر به این مسیر برسد (قاعدهٔ `onPath`، به‌جای همان کلیک).
   * مثلاً کلیک روی کارتِ یک پروژه ← '/projects/'.
   */
  advanceOnPath?: string;
  /** فقط برای این کاربران (نقش/مجوز). نبودن = همه‌ی مخاطبانِ راهنما. */
  when?: (c: TourCtx) => boolean;
  /**
   * اگر عنصر پیدا نشد (مثلاً فهرست خالی است یا آن دکمه برای این کاربر نیست) بی‌صدا رد شود.
   * بدونِ این، کارتِ «این بخش اینجا نیست» با دکمهٔ «بعدی» نشان داده می‌شود.
   */
  optional?: boolean;
  /** جای کارت نسبت به عنصر؛ پیش‌فرض خودکار. */
  placement?: 'top' | 'bottom' | 'start' | 'end';
}

export interface Tour {
  /** شناسهٔ پایدار، مثلاً 'tasks-create'. */
  id: string;
  /** نامِ راهنما در فهرستِ «راهنمای برنامه» — فارسی. */
  title: string;
  /** یک جملهٔ کوتاه دربارهٔ راهنما — فارسی. */
  description: string;
  /** چه کسانی این راهنما را می‌بینند. */
  audience: (c: TourCtx) => boolean;
  /**
   * راهنمای «خوش‌آمد» ِ هر نقش: بارِ اولِ ورود خودکار شروع می‌شود. در هر نقش فقط یکی (اولینِ جورشده)
   * خودکار باز می‌شود؛ بقیه پس از آن پیشنهاد می‌شوند (`next`) یا از فهرست.
   */
  autoStart?: boolean;
  /** ترتیب در فهرست (کوچک‌تر بالاتر). */
  order?: number;
  /** راهنماهای پیشنهادیِ بعد از تمام شدنِ این یکی. */
  next?: string[];
  steps: TourStep[];
}

/** وضعیتِ راهنمای هر کاربر روی سرور (`users.tour_state`). */
export interface TourState {
  /** راهنماهای تمام‌شده ← زمان (ISO). */
  done?: Record<string, string>;
  /** راهنمای در جریان و قدمِ فعلی — تا بعد از رفتن به صفحهٔ دیگر یا بستنِ مرورگر ادامه یابد. */
  active?: { id: string; step: string } | null;
  /** راهنماهایی که مدیر برای این کاربر فرستاده (خودکار شروع می‌شوند، حتی اگر قبلاً دیده). */
  assigned?: string[];
  /** «بعداً» — تا این زمان خودکار شروع نشود (ISO). */
  snoozeUntil?: string;
}
