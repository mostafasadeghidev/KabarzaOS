-- پیوندِ تسک به آیتمِ کتابخانهٔ QA که آن را ساخته — پورتِ نقشهٔ `META_TASKS`.
--
-- ⚠️ بدونِ این، «قبلاً اعمال شده» فقط از روی ردیف‌های چک‌لیست حساب می‌شد و
-- آیتم‌های **تسک‌ساز** هرگز در آن مجموعه نمی‌آمدند؛ نتیجه: هر بار اعمالِ
-- دوبارهٔ یک نقش، تسک‌های تکراری می‌ساخت.
--
-- ⚠️ حذفِ نرمِ تسک خودبه‌خود همان می‌شود: چون مجموعهٔ
-- «اعمال‌شده» تسکِ حذف‌شده را نمی‌شمارد، همان آیتم دوباره قابلِ اعمال است.
alter table tasks
  add column qa_item_id bigint references qa_items(id);

create index tasks_qa_item_ix on tasks (qa_item_id) where qa_item_id is not null;
