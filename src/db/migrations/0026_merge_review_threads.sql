-- رشتهٔ «بازبینی» در رشتهٔ «کامنت» ادغام می‌شود.
--
-- ⚠️ چرا: دو رشتهٔ جدا روی یک پروژه، با مکانیزمِ **یکسان** (رشته، پاسخ،
-- تیکِ باز/بسته) و تنها تفاوتشان نامِ حالتِ بسته («حل شد» به‌جای «انجام شد»).
-- نتیجه سه جای مختلف برای یک کار بود: تسک، کامنت، بازبینی — و هیچ‌کس
-- نمی‌دانست کدام را باید بنویسد.
--
-- ⚠️ بدتر: هیچ شمارنده‌ای رشتهٔ بازبینی را نمی‌دید. داشبورد صریحاً
-- `type = 'comment'` فیلتر می‌کرد و کارتِ «کامنت باز» ِ پروژه، بازبینیِ
-- **حل‌شده** را باز حساب می‌کرد (چون بستهٔ کامنت `done` است و بستهٔ بازبینی
-- `resolved`). پس بازبینی یا نادیده می‌ماند یا عددِ غلط می‌ساخت.
--
-- هیچ داده‌ای از دست نمی‌رود: هر بازبینی یک کامنت می‌شود و «حل شد» به
-- «انجام شد» نگاشت می‌شود — همان معنا با واژگانِ کامنت.
UPDATE comments
SET type = 'comment',
    status = CASE WHEN status = 'resolved' THEN 'done' ELSE status END
WHERE type = 'review';
