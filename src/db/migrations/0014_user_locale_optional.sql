-- زبانِ کاربر اختیاری می‌شود — پورتِ ترتیبِ سه‌مرحله‌ایِ `Core\I18n::current_locale()`.
--
-- ⚠️ چرا null لازم است: نسخهٔ قبلی سه پله دارد — انتخابِ خودِ کاربر، بعد تنظیمِ
-- سراسریِ `default_locale`، بعد پیش‌فرض. با `not null default 'fa'` هیچ‌وقت
-- پلهٔ دوم اجرا نمی‌شد، چون هر کاربر از همان ابتدا مقدار داشت و تنظیمِ
-- سراسری بی‌اثر می‌ماند. null یعنی «خودش انتخابی نکرده» — نه «فارسی».
--
-- ⚠️ ردیف‌های موجود دست نمی‌خورند: کسی که تا امروز 'fa' داشته شاید عمداً
-- فارسی را انتخاب کرده باشد و خالی‌کردنش یعنی تغییرِ خاموشِ زبانش.
alter table users
  alter column locale drop not null;

alter table users
  alter column locale drop default;
